"""Supervised, one-shot AliExpress afterpay execution and durable readback.

Operator: python -m src.payment_executor --help. Preview is the default and
performs only an actual GET for an EXISTING, persisted supplier order. No card
handling, payment-method assumption, payment retry, or scheduler is provided.

Verified official contracts:
https://openservice.aliexpress.com/doc/api.htm?cid=20900#/api?cid=21038&path=aliexpress.ds.order.afterpay&methodType=GET/POST
https://openservice.aliexpress.com/doc/api.htm?cid=20900#/api?cid=21038&path=aliexpress.trade.ds.order.get&methodType=GET/POST
`result: Boolean` acknowledges afterpay, not payment. Only the documented
`order_paidtime_string` on a bound order read proves paid time. No settlement
amount, payment instrument, shipment or delivery is inferred from that field.

Approval JSON is an operator-authored object (not a payment API response):
  approval_id: unique nonempty string; action: aliexpress.ds.order.afterpay;
  supervised: true; supplier_order_id, ebay_order_id, ebay_line_item_id,
  product_id, sku_id: exact strings; quantity: positive JSON integer;
  currency: EUR; checkout_total_eur, source_unit_eur: exact decimal strings;
  expires_at: timezone-aware ISO timestamp, at most 15 minutes ahead.
Source-unit cap excludes freight/tax; checkout total includes the supplier's
actual user-currency order total. No daily budget is inferred. If configured,
MAX_SOURCE_ORDER_TOTAL_EUR is an additional checkout ceiling. A receipt/claim
is never deleted/reissued automatically. --reconcile is the only recovery path.
"""
from contextlib import closing
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from hashlib import sha256
import json
from pathlib import Path
import secrets
import sqlite3

from src.api.aliexpress_client import AliExpressCapabilityError
from src.automation.spending import money, validate_source_unit

METHOD = 'aliexpress.ds.order.afterpay'
ROOT = Path(__file__).resolve().parents[1]


def _now():
    return datetime.now(timezone.utc)


def _stamp(value):
    if not isinstance(value, str):
        raise ValueError('Timezone-aware timestamp required')
    # Official paid-time sample includes a bracketed region after UTC offset.
    text = value.split('[', 1)[0]
    result = datetime.fromisoformat(text.replace('Z', '+00:00'))
    if result.tzinfo is None:
        raise ValueError('Timezone-aware timestamp required')
    return result


def _text(value):
    if (not isinstance(value, str) or not value or value != value.strip()
            or len(value) > 160 or any(ord(c) < 32 for c in value)):
        raise ValueError('Exact bounded identity string required')
    return value


def _db_path(client):
    from sqlalchemy.engine import make_url
    url = make_url(client.config.get('DATABASE_URL') or 'sqlite:///' + (ROOT / 'data/dropshipping.db').as_posix())
    if url.drivername != 'sqlite' or not url.database or url.database == ':memory:':
        raise AliExpressCapabilityError('Payments require the configured durable SQLite order ledger')
    path = Path(url.database)
    return (path if path.is_absolute() else ROOT / path).resolve()


def _connect(path, writable=False):
    # mode=rw never creates an empty substitute order database.
    conn = sqlite3.connect(path.as_uri() + '?mode=' + ('rw' if writable else 'ro'), uri=True, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA busy_timeout=30000')
    if writable:
        conn.execute('PRAGMA synchronous=FULL')
    return conn


def _binding(conn, supplier_order_id, ebay_order_id, ebay_line_item_id):
    rows = conn.execute('''SELECT l.id, l.ebay_order_id, l.ebay_line_item_id,
        l.aliexpress_order_id, l.quantity, l.status, p.aliexpress_product_id, p.sku_id
        FROM order_lines l JOIN products p ON p.id=l.product_id
        WHERE l.aliexpress_order_id=?''', (supplier_order_id,)).fetchall()
    if len(rows) != 1:
        raise AliExpressCapabilityError('Supplier order must belong to exactly one persisted order line')
    row = rows[0]
    if (row['ebay_order_id'] != ebay_order_id or row['ebay_line_item_id'] != ebay_line_item_id
            or type(row['quantity']) is not int or row['quantity'] <= 0):
        raise AliExpressCapabilityError('Persisted supplier/sales order binding mismatch')
    return {'supplier_order_id': supplier_order_id, 'ebay_order_id': ebay_order_id,
            'ebay_line_item_id': ebay_line_item_id, 'product_id': _text(row['aliexpress_product_id']),
            'sku_id': _text(row['sku_id']), 'quantity': row['quantity']}, row['status']


def _approval(path, scope, now):
    # Explicit operator artifact, not generated by this executor or an API flag.
    path = Path(path)
    if path.stat().st_size > 16384:
        raise ValueError('Approval document too large')
    doc = json.loads(path.read_text(encoding='utf-8'))
    if (not isinstance(doc, dict) or doc.get('action') != METHOD or doc.get('supervised') is not True
            or doc.get('currency') != 'EUR'
            or any(type(doc.get(k)) is not type(v) or doc.get(k) != v for k, v in scope.items())):
        raise AliExpressCapabilityError('Exact supervised payment authorization required')
    _text(doc.get('approval_id'))
    expires = _stamp(doc.get('expires_at'))
    if not now < expires <= now + timedelta(minutes=15):
        raise AliExpressCapabilityError('Payment approval expired or exceeds 15-minute supervision window')
    total = money(doc.get('checkout_total_eur'), positive=True)
    unit = money(doc.get('source_unit_eur'), positive=True)
    return dict(scope, approval_id=doc['approval_id'], expires_at=expires.isoformat(),
                currency='EUR', checkout_total_eur=str(total), source_unit_eur=str(unit))


def _eur(value):
    if not isinstance(value, dict) or value.get('currency_code') != 'EUR':
        raise ValueError('Authoritative EUR order amount required')
    return money(value.get('amount'), positive=True)


def _readback(client, scope, approved=None):
    result = client.get_order(scope['supplier_order_id'])
    if result.get('order_id') != scope['supplier_order_id']:
        raise ValueError('Supplier readback identity mismatch')
    children = result.get('child_order_list')
    if isinstance(children, dict):
        children = children.get('ae_child_order_info')
    if not isinstance(children, list) or len(children) != 1 or not isinstance(children[0], dict):
        raise ValueError('Exactly one documented supplier child order required')
    child = children[0]
    count = child.get('product_count')
    # Official Number and its shown integer-string encoding only; no bool/float.
    if isinstance(count, str) and count.isascii() and count.isdigit():
        count = int(count)
    if (str(child.get('product_id')) != scope['product_id'] or child.get('sku_id') != scope['sku_id']
            or type(count) is not int or count != scope['quantity'] or child.get('end_reason')):
        raise ValueError('Supplier child product/SKU/quantity/cancellation mismatch')
    total, unit = _eur(result.get('user_order_amount')), _eur(child.get('product_price'))
    validate_source_unit(unit, client.config)
    if approved and (total != money(approved['checkout_total_eur']) or unit != money(approved['source_unit_eur'])):
        raise ValueError('Checkout amount changed from supervised approval')
    ceiling = client.config.get('MAX_SOURCE_ORDER_TOTAL_EUR')
    if ceiling is not None and total > money(ceiling, positive=True):
        raise ValueError('Configured source-order total cap exceeded')
    paid_at = None
    if result.get('order_paidtime_string'):
        parsed = _stamp(result['order_paidtime_string'])
        if parsed > _now() + timedelta(seconds=30):
            raise ValueError('Supplier paid time is in the future')
        paid_at = parsed.isoformat()
    return {'checkout_total_eur': str(total), 'source_unit_eur': str(unit),
            'observed_at': _now().isoformat(), 'paid_at': paid_at}


def _gates(client):
    from src.runtime import writes_allowed
    client._reload()
    if not writes_allowed(client.config) or any(str(client.config.get(k, '')).lower() != 'true' for k in
            ('ALLOW_ORDER_PURCHASES', 'ALLOW_ORDER_PAYMENTS')):
        raise AliExpressCapabilityError('Payment disabled by runtime write/purchase/payment protection')


@dataclass(frozen=True)
class _PaymentPermit:
    database: Path
    supplier_order_id: str
    secret: str


def consume_transport_authorization(client, params, permit):
    """Low-level gate: consume actual durable scope ONCE before touching HTTP.

    An instance attribute, caller boolean, prepared req, or expired/replayed
    permit cannot authorize a payment. The pending row survives crash/timeout.
    """
    _gates(client)
    if type(permit) is not _PaymentPermit or permit.database != _db_path(client):
        raise AliExpressCapabilityError('Durable scoped payment authorization required')
    if not isinstance(params, dict) or set(params) != {'req'}:
        raise AliExpressCapabilityError('Exactly one scoped payment req required')
    if not isinstance(params['req'], str) or json.loads(params['req']) != {'order_id': permit.supplier_order_id}:
        raise AliExpressCapabilityError('Payment transport order scope mismatch')
    with closing(_connect(permit.database, True)) as conn, conn:
        conn.execute('BEGIN IMMEDIATE')
        row = conn.execute('SELECT * FROM supplier_payment_attempts WHERE supplier_order_id=?',
                           (permit.supplier_order_id,)).fetchone()
        if (row is None or row['state'] != 'claimed' or row['permit_hash'] != sha256(permit.secret.encode()).hexdigest()
                or _stamp(row['expires_at']) <= _now()):
            raise AliExpressCapabilityError('Payment authorization absent, expired, or already consumed')
        scope = json.loads(row['scope_json'])
        current, status = _binding(conn, scope['supplier_order_id'], scope['ebay_order_id'], scope['ebay_line_item_id'])
        if current != scope or status != 'awaiting_payment':
            raise AliExpressCapabilityError('Persisted payment scope changed')
        evidence = json.loads(row['evidence_json'])
        if not timedelta(0) <= _now() - _stamp(evidence['observed_at']) <= timedelta(seconds=60):
            raise AliExpressCapabilityError('Fresh supplier checkout read required')
        validate_source_unit(evidence['source_unit_eur'], client.config)
        ceiling = client.config.get('MAX_SOURCE_ORDER_TOTAL_EUR')
        if ceiling is not None and money(evidence['checkout_total_eur']) > money(ceiling, positive=True):
            raise AliExpressCapabilityError('Configured source-order total cap exceeded')
        conn.execute("UPDATE supplier_payment_attempts SET state='payment_uncertain',permit_hash=NULL WHERE supplier_order_id=?",
                     (permit.supplier_order_id,))


_SCHEMA = '''CREATE TABLE IF NOT EXISTS supplier_payment_attempts(
    supplier_order_id TEXT PRIMARY KEY, ebay_order_id TEXT NOT NULL,
    ebay_line_item_id TEXT NOT NULL, approval_id TEXT NOT NULL UNIQUE,
    scope_json TEXT NOT NULL, evidence_json TEXT NOT NULL, expires_at TEXT NOT NULL,
    permit_hash TEXT, state TEXT NOT NULL, accepted INTEGER, paid_at TEXT,
    created_at TEXT NOT NULL, checked_at TEXT, readback_state TEXT,
    UNIQUE(ebay_order_id,ebay_line_item_id))'''


class PaymentExecutor:
    def __init__(self, client):
        self.client = client
        client._reload()
        self.database = _db_path(client)

    def pay_order(self, supplier_order_id, *, ebay_order_id, ebay_line_item_id,
                  approval_path=None, dry_run=True):
        if type(dry_run) is not bool:
            raise ValueError('dry_run must be boolean')
        self.client.prepare_order_afterpay(supplier_order_id)  # exact ID validation
        _text(ebay_order_id)
        _text(ebay_line_item_id)
        with closing(_connect(self.database)) as conn:
            scope, status = _binding(conn, supplier_order_id, ebay_order_id, ebay_line_item_id)
        if status != 'awaiting_payment':
            raise AliExpressCapabilityError('Only a known created unpaid supplier order is eligible')
        if not dry_run:
            _gates(self.client)
        approved = _approval(approval_path, scope, _now()) if approval_path else None
        if not dry_run and approved is None:
            raise AliExpressCapabilityError('Explicit supervised approval path required')
        evidence = _readback(self.client, scope, approved)
        if dry_run:
            return dict(scope, **evidence, state='preview_only', submitted=False, payment_verified=False,
                        approval_validated=approved is not None, currency='EUR')
        if evidence['paid_at'] is not None:
            raise AliExpressCapabilityError('Supplier already has paid-time evidence; do not submit payment')
        secret = secrets.token_urlsafe(32)
        with closing(_connect(self.database, True)) as conn, conn:
            conn.execute('BEGIN IMMEDIATE')
            conn.execute(_SCHEMA)
            current, status = _binding(conn, supplier_order_id, ebay_order_id, ebay_line_item_id)
            if current != scope or status != 'awaiting_payment':
                raise AliExpressCapabilityError('Persisted payment binding changed before claim')
            try:
                conn.execute('''INSERT INTO supplier_payment_attempts
                    (supplier_order_id,ebay_order_id,ebay_line_item_id,approval_id,scope_json,evidence_json,
                     expires_at,permit_hash,state,created_at) VALUES(?,?,?,?,?,?,?,?,?,?)''',
                    (supplier_order_id, ebay_order_id, ebay_line_item_id, approved['approval_id'],
                     json.dumps(scope, sort_keys=True), json.dumps(evidence), approved['expires_at'],
                     sha256(secret.encode()).hexdigest(), 'claimed', _now().isoformat()))
            except sqlite3.IntegrityError:
                raise AliExpressCapabilityError('Payment already claimed; reconcile only, never repeat') from None
        permit = _PaymentPermit(self.database, supplier_order_id, secret)
        accepted = None
        try:
            envelope = self.client._request(METHOD, self.client.prepare_order_afterpay(supplier_order_id)['params'],
                                            payment_authorization=permit)
            # No guessed rsp_code vocabulary: transport rejects business errors;
            # only a real JSON Boolean is the documented acknowledgement.
            if type(envelope.get('result')) is bool:
                accepted = envelope['result']
        except Exception:
            # Never leak raw provider data. Any attempted/claimed write remains
            # non-repeatable even if the guard, provider or response fails.
            pass
        with closing(_connect(self.database, True)) as conn, conn:
            conn.execute("UPDATE supplier_payment_attempts SET state=CASE WHEN state='paid' THEN state ELSE ? END,accepted=?,permit_hash=NULL WHERE supplier_order_id=?",
                         ('payment_requested_awaiting_confirmation' if accepted is True else 'payment_uncertain',
                          None if accepted is None else int(accepted), supplier_order_id))
        return self.reconcile(supplier_order_id)

    def reconcile(self, supplier_order_id):
        """Read-only provider reconciliation; never calls afterpay, even if unpaid.

        This updates only our additive receipt table, not finance/fulfillment or
        order-line states owned by other subsystems. Unknown/mismatched reads
        retain the original durable state and an explicit readback blocker.
        """
        self.client.prepare_order_afterpay(supplier_order_id)
        with closing(_connect(self.database)) as conn:
            row = conn.execute('SELECT * FROM supplier_payment_attempts WHERE supplier_order_id=?',
                               (supplier_order_id,)).fetchone()
            if row is None:
                raise AliExpressCapabilityError('No persisted payment attempt to reconcile')
            row = dict(row)
            scope = json.loads(row['scope_json'])
            current, _ = _binding(conn, supplier_order_id, scope['ebay_order_id'], scope['ebay_line_item_id'])
        state, paid_at, readback = row['state'], row['paid_at'], 'unavailable_or_mismatched'
        try:
            if current != scope:
                raise ValueError('Persisted scope changed')
            evidence = _readback(self.client, scope, json.loads(row['evidence_json']))
            readback = 'bound_paid_time' if evidence['paid_at'] else 'bound_without_paid_time'
            if evidence['paid_at']:
                state, paid_at = 'paid', evidence['paid_at']
        except Exception:
            pass
        if state == 'claimed':
            state = 'payment_uncertain'  # crashed pre-submit claims are never reissued
        with closing(_connect(self.database, True)) as conn, conn:
            conn.execute('''UPDATE supplier_payment_attempts SET
                state=CASE WHEN state='paid' THEN state ELSE ? END,
                paid_at=COALESCE(paid_at,?),checked_at=?,readback_state=?,permit_hash=NULL
                WHERE supplier_order_id=?''', (state, paid_at, _now().isoformat(), readback, supplier_order_id))
            stored = conn.execute('SELECT state,paid_at,readback_state,accepted FROM supplier_payment_attempts WHERE supplier_order_id=?',
                                  (supplier_order_id,)).fetchone()
        return dict(scope, state=stored['state'], payment_verified=stored['state'] == 'paid',
                    paid_at=stored['paid_at'], readback_state=stored['readback_state'],
                    accepted=None if stored['accepted'] is None else bool(stored['accepted']),
                    retry_allowed=False, settlement_amount_verified=False)


def main(argv=None):
    import argparse
    from src.api.aliexpress_client import AliExpressAPIClient
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, help='Explicit configuration path; default project .env')
    parser.add_argument('--supplier-order-id', required=True)
    parser.add_argument('--ebay-order-id')
    parser.add_argument('--ebay-line-item-id')
    parser.add_argument('--approval-path', type=Path)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--execute', action='store_true', help='Submit exactly once with live/purchase/payment gates and supervised approval')
    action.add_argument('--reconcile', action='store_true', help='Read persisted attempt; never submit payment')
    args = parser.parse_args(argv)
    if not args.reconcile and (not args.ebay_order_id or not args.ebay_line_item_id):
        parser.error('Preview/execution requires exact eBay order and line identifiers')
    if args.execute and not args.approval_path:
        parser.error('--execute requires --approval-path')
    try:
        executor = PaymentExecutor(AliExpressAPIClient(args.config))
        result = (executor.reconcile(args.supplier_order_id) if args.reconcile else
                  executor.pay_order(args.supplier_order_id, ebay_order_id=args.ebay_order_id,
                                     ebay_line_item_id=args.ebay_line_item_id,
                                     approval_path=args.approval_path, dry_run=not args.execute))
    except Exception:
        print(json.dumps({'state': 'blocked', 'reason': 'payment_scope_gates_or_readback_unverified'}))
        return 2
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
