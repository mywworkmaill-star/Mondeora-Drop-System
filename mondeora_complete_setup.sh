echo "📋 Yapmış olmanız gerekenler:"
echo "   1. console.anthropic.com → Login"
echo "   2. API Keys → ESKİ KEY'İ SİLİN (sk-ant-usr-18FApX...)"
echo "   3. Create Key → Yeni key oluşturun"
echo "   4. Key'i kopyalayın"
echo ""
echo "════════════════════════════════════════════════════════════════════════"
echo ""

# API Key iste
read -p "🔑 Anthropic API Key (sk-ant- ile başlar): " API_KEY

# Boşsa atla
if [ -z "$API_KEY" ]; then
    echo ""
    echo "⏭️  API key girilmedi, mevcut config korunuyor"
    echo ""
else
    # Doğrulama
    if [[ ! $API_KEY =~ ^sk-ant- ]]; then
        echo ""
        echo "❌ HATA: Geçersiz API key formatı!"
        echo "   Anthropic key'leri 'sk-ant-' ile başlamalı"
        echo ""
        exit 1
    fi

    echo ""
    echo "✅ API key geçerli, config'e ekleniyor..."

    # Yeni config oluştur (tüm ayarlarla)
    cat > "$CONFIG_FILE" << EOF
# ════════════════════════════════════════════════════════════════════════════
# HERMES CONFIGURATION
# Auto-generated by Mondeora Setup Script
# ════════════════════════════════════════════════════════════════════════════

# Anthropic API Configuration
anthropic:
  api_key: "$API_KEY"

# Default Model Selection
defaults:
  model: claude-sonnet-4-5-20250929
  provider: anthropic

# Model Configuration
models:
  claude-sonnet-4.5:
    provider: anthropic
    model: claude-sonnet-4-5-20250929
    max_tokens: 8192
    temperature: 1.0

# Session Settings
session:
  auto_save: true
  max_history: 100

# Skills Settings
skills:
  enabled: true
  auto_load: true

# Desktop UI Settings (eğer desktop app kullanıyorsanız)
ui:
  theme: auto
  font_size: 14
EOF

