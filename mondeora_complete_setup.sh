name: mondeora_inventory_sync
schedule: "0 */4 * * *"
command: |
  cd /c/Users/Administrator/Desktop/Mondeora-Drop-System
  "/c/Program Files/Python311/python.exe" auto_inventory_sync.py
enabled: true
EOFCRON
