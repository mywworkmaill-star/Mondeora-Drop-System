name: mondeora_log_cleanup
schedule: "0 4 * * 0"
command: |
  cd /c/Users/Administrator/Desktop/Mondeora-Drop-System
  find logs -name "*.log" -mtime +30 -delete
enabled: true
EOFCRON
echo "✅ [7/7] Log cleanup (weekly)"

echo ""

