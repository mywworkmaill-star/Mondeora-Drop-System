echo "════════════════════════════════════════════════════════════════════════"
echo "🚀 MONDEORA COMPLETE SETUP"
echo "════════════════════════════════════════════════════════════════════════"
echo "⏰ Başlangıç: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

# ════════════════════════════════════════════════════════════════════════════
# BÖLÜM 1: ANTHROPIC API KEY + MODEL KURULUMU
# ════════════════════════════════════════════════════════════════════════════
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
