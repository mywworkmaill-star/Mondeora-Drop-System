# ════════════════════════════════════════════════════════════════════════════
# BÖLÜM 2: SİSTEM ONARIM
# ════════════════════════════════════════════════════════════════════════════
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
