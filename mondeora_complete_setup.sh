    echo ""
    echo "📋 Yapılan ayarlar:"
    echo "   ✅ API Key eklendi"
    echo "   ✅ Model: Claude Sonnet 4.5 (claude-sonnet-4-5-20250929)"
    echo "   ✅ Provider: Anthropic"
    echo "   ✅ Max tokens: 8192"
